# Python Variables and Data Types

# Employee Profile
employee_name = "Alex" # String
employee_id = 2525 # Integer
experience = 3.5 # Float
annual_salary = 450000 # Integer
is_active = True # Boolean

print("Employee Profile:")
print("Employee Name -", employee_name)
print("Employee ID -", employee_id)
print("Experience -", experience)
print("Annual Salary -", annual_salary)
print("Active Status -", is_active)

# Check Datatypes
print("Data Types:")
print("Type of employee_name:", type(employee_name))
print("Type of employee_id:", type(employee_id))
print("Type of experience:", type(experience))
print("Type of annual_salary:", type(annual_salary))
print("Type of is_active:", type(is_active))